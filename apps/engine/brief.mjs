import { readFile, writeFile, mkdir, access } from "node:fs/promises";
import { join } from "node:path";
import { EngineError, localDate } from "./store.mjs";

// The operating brief (index.md) is generated from engine state, not written
// by hand. It stays small because it summarizes current state and links to
// history instead of accumulating it.
export const BRIEF_LIMIT = 2048;
export const GENERATED_MARK = "<!-- generated by the marketing engine; edit engine.json or state, not this file -->";

// Picks the single most useful next step from state, in order of urgency.
// The rules are fixed, so two runs over the same state agree on what comes next.
export function nextAction(view, config) {
  const [blocked] = view.unresolved;
  if (blocked)
    return blocked.status === "handoff"
      ? `Post ${blocked.actionId} manually, then record its receipt.`
      : `Reconcile delivery ${blocked.id} (${blocked.status}) before sending anything else.`;
  if (!Object.keys(config.channels).length) return "Owner: configure a publishing channel in engine.json.";
  if (!view.grants.length) return "Owner: grant or approve publishing in a terminal.";
  const open = view.grants.find((grant) => grant.usedToday < grant.maxPerDay);
  if (open && view.proposed.length)
    return `Publish ${view.proposed[0].id} to ${view.proposed[0].channel}.`;
  if (open) return `Propose today's ${open.channel} post with one tagged variable.`;
  return "Pull results and record a decision; today's allowance is used.";
}

function attention(view, config) {
  const items = [];
  for (const item of view.unresolved)
    items.push(
      item.status === "handoff"
        ? `Post on ${item.channel}: content via \`engine show ${item.actionId}\`, then record its receipt.`
        : `Delivery ${item.id} for ${item.actionId} on ${item.channel} is ${item.status}; reconcile it.`,
    );
  if (!view.grants.length && Object.keys(config.channels).length)
    items.push("No active publishing grant: posts need one-off owner approval.");
  for (const grant of view.grants) {
    const days = Math.floor((Date.parse(grant.expiresAt) - Date.parse(view.at)) / 86_400_000);
    if (days <= 7) items.push(`Grant ${grant.id} (${grant.channel}) expires in ${days} day(s).`);
  }
  if (!config.northStar) items.push("No north-star metric configured, so results cannot guide decisions.");
  else if (!view.northStar.last7.knownDays)
    items.push(`No ${config.northStar} readings in the last 7 days; check the metric connection.`);
  return items;
}

const value = (summary) =>
  summary.averagePerDay === null ? "unknown" : `${summary.averagePerDay}/day (${summary.knownDays} days known)`;

export function renderBrief(view, config, links) {
  const lines = [
    `# ${config.name ?? "Marketing"}`,
    "",
    GENERATED_MARK,
    `Updated: ${view.at.slice(0, 10)}`,
    "",
    `**Confirmed goal:** ${config.goal ?? "Not set in engine.json."}`,
    "",
    `**Next action:** ${nextAction(view, config)}`,
    "",
  ];
  if (view.northStar)
    lines.push(
      `**North star (${view.northStar.metric}):** last 7 days ${value(view.northStar.last7)}; prior 7 ${value(view.northStar.prior7)}.`,
      "",
    );
  lines.push("## Needs your attention", "");
  const items = attention(view, config);
  lines.push(...(items.length ? items.map((item) => `- ${item}`) : ["- Nothing blocked."]), "");
  if (view.recentDeliveries.length) {
    lines.push("## Recent posts", "");
    for (const post of view.recentDeliveries.slice(0, 3))
      lines.push(`- ${post.localDate} ${post.channel}: ${post.status}${post.url ? ` ${post.url}` : ""}`);
    lines.push("");
  }
  if (links.length) {
    lines.push("| Record | Status |", "| --- | --- |");
    for (const link of links) lines.push(`| [${link.title}](${link.path}) | ${link.status} |`);
    lines.push("");
  }
  const brief = lines.join("\n");
  if (Buffer.byteLength(brief) > BRIEF_LIMIT)
    throw new EngineError("brief_too_large", `Generated brief exceeds ${BRIEF_LIMIT} bytes; shorten config text.`);
  return brief;
}

// Writes reports/engine-snapshot.json for the read-only dashboard: one
// daily series per configured metric over the last 28 days, dated in that
// metric's own time zone. Unreadable days are kept as null so the chart shows
// a gap, not a dip to zero. Select it in dashboard.json with
// "/metrics/<name>/latest" and series pointer "/metrics/<name>/daily".
export async function writeSnapshot(db, brandDir, config, now = new Date()) {
  const since = new Date(now.getTime() - 28 * 86_400_000).toISOString();
  const metrics = {};
  for (const metric of config.metrics) {
    const daily = db
      .prepare(
        `SELECT value, window_start FROM observations
         WHERE metric = ? AND action_id IS NULL AND is_current = 1 AND window_start >= ?
         ORDER BY window_start`,
      )
      .all(metric.name, since)
      .map((row) => ({ date: localDate(new Date(row.window_start), metric.timezone), value: row.value }));
    const lastKnown = daily.findLast((day) => day.value !== null) ?? null;
    metrics[metric.name] = {
      event: metric.event,
      type: metric.type,
      timezone: metric.timezone,
      latest: lastKnown?.value ?? null,
      latestDate: lastKnown?.date ?? null,
      daily,
    };
  }
  await mkdir(join(brandDir, "reports"), { recursive: true });
  await writeFile(
    join(brandDir, "reports/engine-snapshot.json"),
    `${JSON.stringify({ observedAt: now.toISOString(), metrics }, null, 2)}\n`,
  );
  return { path: "reports/engine-snapshot.json", metrics: Object.keys(metrics) };
}

const exists = (path) => access(path).then(() => true, () => false);

// Writes index.md. A hand-written brief is archived under reports/archive/
// before the first replacement, never overwritten in place.
export async function writeBrief(brandDir, view, config, { replaceManual = false } = {}) {
  const path = join(brandDir, "index.md");
  let current = null;
  try {
    current = await readFile(path, "utf8");
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  let archived = null;
  if (current !== null && !current.includes(GENERATED_MARK)) {
    if (!replaceManual)
      throw new EngineError(
        "manual_brief",
        "index.md was written by hand. Pass --replace-manual-brief to archive it and switch to the generated brief.",
      );
    archived = `reports/archive/index-${view.at.slice(0, 10)}.md`;
    await mkdir(join(brandDir, "reports/archive"), { recursive: true });
    if (await exists(join(brandDir, archived)))
      throw new EngineError("archive_exists", `${archived} already exists; refusing to overwrite it.`);
    await writeFile(join(brandDir, archived), current);
  }
  const links = [];
  for (const [title, file, status] of [
    ["Decisions", "strategy/decisions.md", "Strategic decisions"],
    ["Learning", "reports/learning.md", "Evidence-linked lessons"],
    ...(archived ? [["Previous brief", archived, "Archived hand-written brief"]] : []),
  ])
    if (await exists(join(brandDir, file))) links.push({ title, path: file, status });
  const brief = renderBrief(view, config, links);
  await writeFile(path, brief);
  return { path: "index.md", bytes: Buffer.byteLength(brief), archived };
}
